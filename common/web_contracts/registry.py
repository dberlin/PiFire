class ContractBundle:
    name: str
    models: tuple[type[BaseModel], ...]
    typescript_output: str


@dataclass(frozen=True, slots=True)
class RootContract:
    name: str
    model: type[BaseModel]
    schema_output: str
    typescript_output: str


